"""地区词表与城市提取（GEO「本地」问法共用一份口径）。

2026-09-23（Owner 点名：「监测这里，行业还是国内，不是成都……问的时候要加本地」）：
「所在地」原先只在入驻时用于竞品发现（「成都本地的家装都有哪些公司？」），
监测探针里却写死了「国内{行业}平台有哪些？」——同一个企业，两处口径不一致。

把城市表与抠取逻辑从 onboard 抽到这里，让 **入驻（发现同行）** 与
**监测（探针问句）** 用同一份城市表，不各留一套。
"""
CITIES = [
    "北京", "上海", "广州", "深圳", "成都", "杭州", "重庆", "武汉", "西安", "苏州", "天津", "南京",
    "郑州", "长沙", "东莞", "青岛", "沈阳", "宁波", "昆明", "大连", "厦门", "合肥", "佛山", "福州",
    "哈尔滨", "济南", "无锡", "长春", "温州", "石家庄", "南宁", "常州", "泉州", "南昌", "贵阳", "太原",
    "烟台", "嘉兴", "南通", "金华", "珠海", "惠州", "徐州", "海口", "乌鲁木齐", "绍兴", "中山", "台州",
    "兰州", "潍坊", "保定", "镇江", "扬州", "桂林", "唐山", "三亚", "湖州", "汕头", "新乡", "廊坊",
    "呼和浩特", "赣州", "盐城", "泰州", "洛阳", "宜昌", "襄阳", "绵阳", "泸州", "遵义",
]


def extract_city(text: str) -> str:
    """从文本里提取城市（「成都笔革设计公司」→「成都」）；提取不到返回空。

    这是**兜底**：入驻页有「所在地」输入框，用户填了就用用户填的 ——
    「笔革家居」这种名字里没城市的，靠抠名字永远抠不出来（实测退化成全国结果）。
    """
    for c in CITIES:
        if c in (text or ""):
            return c
    return ""


def clean_city(text: str) -> str:
    """用户填的所在地 → 探针里用的城市名（「成都市」→「成都」；填不出城市就原样返回短词）。"""
    t = (text or "").strip()
    if not t:
        return ""
    # 「成都市」「苏州 市」这类带行政后缀的写法：先按城市表归一
    hit = extract_city(t)
    if hit:
        return hit
    # 词表里没有的小城市：去掉尾部「市」，别把「XX市的」念出来
    if len(t) > 1 and t.endswith("市"):
        return t[:-1].strip()
    return t
